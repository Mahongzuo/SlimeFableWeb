import {modeById} from '../../content/daily-modes';
import {levels} from '../../content/levels/registry';
import {isWorkshop} from '../../content/turning-season';
import {isDecemberChapter} from '../templates/december-chapters';
import {isNewyearChapter} from '../../content/chronicle-newyear';
import {isMonthendChapter} from '../templates/monthend-chapters';
import {isYearendChapter} from '../templates/yearend-chapters';
import {isMidwinterChapter} from '../templates/midwinter-chapters';
import {isWinterChapter} from '../templates/winter-chapters';
import {isSecond} from '../templates/season-second';
/** level.html?id=MMDD-YYYY → the chapter's template decides which runtime loads. */
const id = new URLSearchParams(location.search).get('id') ?? '';
const mode = modeById(id);
const spec = levels[id];
if(mode||spec)void import('./level-help').then(({installGateHelp})=>installGateHelp(id));
if (mode?.january && mode.kind==='defense') import('./january-defense');
else if (mode?.kind==='skirmish' && ((mode.day>='1127' && mode.day<='1231') || (mode.day>='0102' && mode.day<='0110'))) import('./season-skirmish');
else if (mode?.january && mode.kind==='skirmish') import('./january-skirmish');
else if (mode?.january && mode.kind==='rpg') import('./january-rpg');
else if (mode?.kind === 'defense') import('./defense');
else if (mode?.kind === 'match') import('./mode-match');
else if (mode?.kind==='skirmish'||mode?.kind==='rpg') import('./battle-preview');
else if (mode) import('./mode-world');
else if (isWorkshop(id)) import('./turning-season');
else if (isNewyearChapter(id)) import('./newyear-chapters');
else if (isMonthendChapter(id)) import('./monthend-chapters');
else if (isYearendChapter(id)) import('./yearend-chapters');
else if (isMidwinterChapter(id)) import('./midwinter-chapters');
else if (isWinterChapter(id)) import('./winter-chapters');
else if (isDecemberChapter(id)) import('./december-chapters');
else if (isSecond(id)) import('./season-second');
else if (spec?.template === 'jan01-seal') import('./jan01-seal');
else if (spec?.template === 'jan01-book') import('./jan01-book');
else if (spec?.template === 'runner') import('./runner');
else if (spec?.template === 'lander') import('./lander');
else if (spec?.template === 'flyby') import('./flyby');
else if (spec?.template === 'landmark') import('./landmark');
else if (spec?.template === 'almanac') import('./almanac');
else if (spec?.template === 'solstice') import('./solstice');
else if (spec?.template === 'folio') import('./folio');
else if (spec?.template === 'ability') import('./ability');
else if (spec?.template === 'chronicle') import('./chronicle');
else if (spec?.template === 'atlas') import('./atlas');
else import('./explore');
