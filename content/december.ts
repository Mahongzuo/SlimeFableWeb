export const decemberDays: DayMeta[] = decemberLevels.map(s => {
  const [day, year] = s.id.split('-');
  return {
    day,
    theme: s.title,
    chapters: [{
      id: s.id,
      day,
      year: Number(year),
      event: s.fact.replace(/。$/, ''),
      quest: s.title,
      steps: [...s.stops, s.finale],
      souvenir: s.souvenir,
      template: s.template,
      era: s.biome,
      tone: s.tone,
      status: 'web',
      palette: s.palette,
    }],
  };
});
