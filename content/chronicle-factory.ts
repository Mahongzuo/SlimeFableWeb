import type {
  ChronicleLandmark,
  ChronicleMode,
  ChronicleSpec,
  ChronicleTheme,
} from './levels/types';

export type ChronicleRow = [
  id: string,
  region: 'cn' | 'intl',
  slot: 1 | 2,
  tone: 'bright' | 'solemn',
  mode: ChronicleMode,
  theme: ChronicleTheme,
  landmark: ChronicleLandmark,
  element: number,
  title: string,
  fact: string,
  source: string,
  intro: string,
  storyNotes: [string, string, string],
  outro: string,
  relicName: string,
  finaleLabel: string,
  souvenir: string,
  palette: [string, string],
  medals: [number, number],
];

export function expandChronicles(rows: ChronicleRow[]): ChronicleSpec[] {
  return rows.map(
    ([
      id,
      region,
      slot,
      tone,
      mode,
      theme,
      landmark,
      element,
      title,
      fact,
      source,
      intro,
      storyNotes,
      outro,
      relicName,
      finaleLabel,
      souvenir,
      palette,
      [gold, silver],
    ]) => ({
      id,
      template: 'chronicle',
      region,
      slot,
      tone,
      mode,
      theme,
      landmark,
      element,
      title,
      fact,
      source,
      intro,
      storyNotes,
      outro,
      relicName,
      finaleLabel,
      souvenir,
      palette,
      medals: {gold, silver},
    }),
  );
}
